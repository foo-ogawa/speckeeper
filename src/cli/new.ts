/**
 * New Command
 *
 * Generate templates for new model instances
 */

import chalk from 'chalk';
import { join } from 'node:path';
import { writeFileSync, existsSync } from 'node:fs';
import { loadConfig } from '../utils/config-loader.js';
import { getSpecsFromConfig } from '../core/model.js';

// ============================================================================
// Types
// ============================================================================

export interface NewCommandOptions {
  /** Name of the element */
  name?: string;
  output?: string;
  dryRun?: boolean;
}

/** The model surface `new` reads */
interface NewElementModel {
  id: string;
  name: string;
  idPrefix: string;
}

// ============================================================================
// New Command
// ============================================================================

/** Create an element of the model `type`, one of the models the config registers */
export async function newCommand(type: string, options: NewCommandOptions): Promise<void> {
  console.log(chalk.blue('speckeeper new'));
  console.log('');

  const cwd = process.cwd();
  const config = await loadConfig();
  const models = (config.models ?? []) as NewElementModel[];
  const model = models.find(m => m.id === type);

  if (!model) {
    console.error(chalk.red(`  Error: Unknown model type '${type}'`));
    console.error(chalk.gray(`  Model types the config registers: ${models.map(m => m.id).join(', ') || '(none)'}`));
    process.exitCode = 1;
    return;
  }

  const id = nextId(model.idPrefix, getSpecsFromConfig(config.specs, model.id));
  const template = generateTemplate(model, id, options.name);

  if (options.dryRun) {
    console.log(chalk.gray('  Template (dry run):'));
    console.log('');
    console.log(template);
    return;
  }

  // Write template to file
  const outputDir = options.output || join(cwd, config.designDir || 'design');
  const outputFile = join(outputDir, `${model.id}-${id}.ts`);

  if (existsSync(outputFile)) {
    console.error(chalk.red(`  Error: File already exists: ${outputFile}`));
    process.exitCode = 1;
    return;
  }

  writeFileSync(outputFile, template);
  console.log(chalk.green(`  ✓ Created: ${outputFile}`));
}

/**
 * The ID after the highest `<prefix>-<number>` among the model's elements, with
 * as many digits; `<prefix>-001` for the first one.
 */
function nextId(prefix: string, specs: unknown[]): string {
  let highest = 0;
  let digits = 3;
  for (const spec of specs) {
    const id = (spec as { id?: unknown }).id;
    if (typeof id !== 'string' || !id.startsWith(`${prefix}-`)) continue;
    const number = id.slice(prefix.length + 1);
    if (!/^\d+$/.test(number) || Number(number) < highest) continue;
    highest = Number(number);
    digits = number.length;
  }
  return `${prefix}-${String(highest + 1).padStart(digits, '0')}`;
}

// ============================================================================
// Template Generation
// ============================================================================

/**
 * The element as a TypeScript module. It imports nothing, so it compiles
 * wherever it is placed; the model's schema checks it once it is added to the
 * model's specs.
 */
function generateTemplate(model: NewElementModel, id: string, name: string | undefined): string {
  const lines: string[] = [];

  lines.push(`/**`);
  lines.push(` * ${model.name}: ${id}`);
  lines.push(` * `);
  lines.push(` * Generated by speckeeper new. Add it to the specs of the ${model.id} model.`);
  lines.push(` */`);
  lines.push(`export const ${camelCase(id)} = {`);
  lines.push(`  id: ${JSON.stringify(id)},`);
  if (name !== undefined) lines.push(`  name: ${JSON.stringify(name)},`);
  lines.push(`  // TODO: Fill in the fields the ${model.id} model requires`);
  lines.push(`};`);
  lines.push('');

  return lines.join('\n');
}

function camelCase(str: string): string {
  return str
    .toLowerCase()
    .replace(/[-_](.)/g, (_, c) => c.toUpperCase());
}
